"""Export reviewed upstream prompt constants without executing the Python pipeline."""
import ast
import hashlib
import json
from pathlib import Path

plugin = Path(__file__).resolve().parents[1]
source = plugin.parent / "SciAtlas"
prompt_path = source / "sciatlas_idea_gen/prompts.py"
tree = ast.parse(prompt_path.read_text(encoding="utf-8"))
prompts = {}
for node in tree.body:
    if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
        for target in node.targets:
            if isinstance(target, ast.Name):
                prompts[target.id] = node.value.value
(plugin / "src/research/upstream-prompts.ts").write_text(
    '/** Reviewed SciAtlas idea-generation templates; regenerated by scripts/sync-prompts.py. */\n'
    + 'export const upstreamPrompts = '
    + json.dumps(prompts, ensure_ascii=False, indent=2)
    + ' as const\n', encoding="utf-8")
review_path = source / "review_pipeline/review/idea_rubric.py"
review_prompts = {}
for node in ast.parse(review_path.read_text(encoding="utf-8")).body:
    if isinstance(node, ast.Assign):
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id.endswith("SYSTEM_PROMPT"):
                value = ast.literal_eval(node.value)
                if isinstance(value, str):
                    review_prompts[target.id] = value
(plugin / "src/research/upstream-review-prompts.ts").write_text(
    '/** Reviewed SciAtlas rubric prompts; exported without running the pipeline. */\n'
    + 'export const reviewPrompts = ' + json.dumps(review_prompts, ensure_ascii=False, indent=2)
    + ' as const\n', encoding="utf-8")
references = [
    "sciatlas/src/sciatlas/cli.py", "sciatlas/src/sciatlas/skills.py",
    "literature_review_pipeline/downstream/lr_search/literature_review_search.py",
    "literature_review_pipeline/downstream/lr_search/generate_literature_review_report.py",
    "review_pipeline/pipeline.py", "review_pipeline/review/idea_rubric.py",
    "sciatlas/evidence/grounding.py", "sciatlas_idea_gen/pipeline.py",
    "sciatlas_idea_gen/config.py", "sciatlas_idea_gen/prompts.py",
]
baseline = {"date": "2026-10-11", "source": "current SciAtlas working tree", "sha256": {
    path: hashlib.sha256((source / path).read_bytes()).hexdigest() for path in references
}}
(plugin / "docs").mkdir(exist_ok=True)
(plugin / "docs/migration-baseline.json").write_text(json.dumps(baseline, indent=2) + '\n', encoding="utf-8")
